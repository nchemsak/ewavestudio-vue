// scripts/render-drum-kit.mjs
// Renders the Drums machine's frozen kit (src/audio/drumKit.ts) into src/audio/drumKitData.ts.
//
// The first kit's four (PR 119: Kick, Snare, Metal and the old Hat, "Tin hat" on screen) were
// one-shots of the app's own Rhythm presets; they're frozen, so this script copies them from the
// current drumKitData.ts unchanged (saved projects play them). The sounds added in PR 135 (the
// plan's item 17) are rendered here from scripts/drum-recipes.js, in Chromium (an
// OfflineAudioContext; no app or server needed), each at its recipe's sample rate.
//
// Each new sound is cut where it stays 46 dB under its peak (with a 10 ms fade), set to −1 dBFS
// and kept as 16-bit PCM in base64, as the first four were.
//
// Run it only to change the kit, and add a sound only under a new id: a saved project's slot
// names its sound ('kit:tom'), so changing a sound that's there changes saved projects.
//   node scripts/render-drum-kit.mjs
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';

const DATA = new URL('../src/audio/drumKitData.ts', import.meta.url);
const FROZEN = ['kick', 'snare', 'metal', 'hat'];
const recipes = readFileSync(new URL('./drum-recipes.js', import.meta.url), 'utf8');

// The frozen four, as they are
const frozen = {};
for (const m of readFileSync(DATA, 'utf8').matchAll(/\t(\w+): \{ sampleRate: (\d+), data: '([^']+)' \}/g)) {
	if (FROZEN.includes(m[1])) frozen[m[1]] = { sampleRate: +m[2], data: m[3] };
}
for (const id of FROZEN) if (!frozen[id]) throw new Error(`drumKitData.ts has no ${id}: get it back from git history`);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.addScriptTag({ content: `${recipes}\nwindow.DRUM_RECIPES = DRUM_RECIPES;` });
const rendered = await page.evaluate(async () => {
	// The same seeded numbers every run (an LCG), so a render is repeatable
	const seeded = (s) => () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
	const out = {};
	for (const [id, rcp] of Object.entries(window.DRUM_RECIPES)) {
		const ctx = new OfflineAudioContext(1, rcp.rate * 2, rcp.rate);
		const rings = rcp.play(ctx, ctx.destination, seeded(7));
		const d = (await ctx.startRendering()).getChannelData(0);
		let peak = 0;
		for (const v of d) peak = Math.max(peak, Math.abs(v));
		let end = Math.min(d.length, Math.ceil((rings + 0.02) * rcp.rate));
		while (end > 1 && Math.abs(d[end - 1]) < peak * 0.005) end--;
		end = Math.min(d.length, end + Math.round(0.01 * rcp.rate));
		const x = Array.from(d.slice(0, end), (v) => (v / peak) * 0.891);
		const fade = Math.min(x.length, Math.round(0.01 * rcp.rate));
		for (let i = 0; i < fade; i++) x[x.length - 1 - i] *= i / fade;
		out[id] = { rate: rcp.rate, x };
	}
	return out;
});
await browser.close();

const kit = { ...frozen };
for (const [id, { rate, x }] of Object.entries(rendered)) {
	const bytes = Buffer.alloc(x.length * 2);
	x.forEach((v, i) => bytes.writeInt16LE(Math.round(Math.max(-1, Math.min(1, v)) * 32767), i * 2));
	kit[id] = { sampleRate: rate, data: bytes.toString('base64') };
	console.log(`${id}: ${(x.length / rate).toFixed(3)} s at ${rate} Hz, ${kit[id].data.length} characters`);
}

const lines = Object.entries(kit).map(([id, s]) => `\t${id}: { sampleRate: ${s.sampleRate}, data: '${s.data}' },`);
writeFileSync(DATA, `// src/audio/drumKitData.ts
// GENERATED by scripts/render-drum-kit.mjs: the Drums machine's frozen kit (drumKit.ts), each
// sound a one-shot as 16-bit PCM in base64. Don't edit by hand.
import type { SampleData } from './sample';
import type { KitId } from './drums';

export const DRUM_KIT: Record<KitId, SampleData> = {
${lines.join('\n')}
};
`);
console.log('Wrote src/audio/drumKitData.ts');
